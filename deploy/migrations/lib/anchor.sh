# anchor.sh — anchored-edit helpers for `actions.toml`-style files, sourced by new migrations
# (deploy/migrations/README.md mandates it; plan tn-review-2026-11-04-remediation WP-R6).
#
#   anchor_id_line <file> <id>      print the (1-based) line of `id = "<id>"`, fully anchored: only blanks around
#                                   it, so `id = "<id>-x"` never matches; exit 1 when absent
#   anchor_block_end <file> <line>  print the last line of the block whose id line is <line>: the line before
#                                   the next `[[action]]` header, or the last line of the file
#   anchor_has_key <file> <line> <key>  exit 0 when a `<key> =` line sits in that block (nested
#                                   `[[action.steps]]` tables are part of the block)
#   anchor_insert_after <file> <line> <text>  rewrite <file> with <text> inserted after <line>
#   anchor_replace <tmp> <file>     replace <file>'s content with <tmp>'s (cat, keeps inode and mode), removing <tmp>
#   anchor_die <msg>...             print `    <msg>` on stderr and return 1
# Bash + coreutils + awk only.
