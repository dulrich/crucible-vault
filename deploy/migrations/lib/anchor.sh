anchor_die() {
  echo "    $*" >&2
  return 1
}

anchor_id_line() {
  local n
  n=$(grep -En "^[[:space:]]*id[[:space:]]*=[[:space:]]*\"$2\"[[:space:]]*\$" "$1" | head -n 1 | cut -d: -f1 || true)
  [[ -n $n ]] || return 1
  echo "$n"
}

anchor_block_end() {
  local e
  e=$(awk -v s="$2" 'NR>s && /^[[:space:]]*\[\[action\]\]/ {print NR - 1; exit}' "$1")
  [[ -n $e ]] || e=$(wc -l <"$1")
  echo "$e"
}

anchor_has_key() {
  local end
  end=$(anchor_block_end "$1" "$2")
  awk -v s="$2" -v e="$end" -v k="$3" '
    NR>s && NR<=e && $0 ~ "^[[:space:]]*" k "[[:space:]]*=" {f=1}
    END {exit !f}' "$1"
}

anchor_insert_after() {
  local t
  t=$(mktemp)
  awk -v n="$2" -v text="$3" '{print} NR==n {print text}' "$1" >"$t"
  anchor_replace "$t" "$1"
}

anchor_replace() {
  cat "$1" >"$2"
  rm -f "$1"
}

anchor_array_add() {
  local f=$1 table=$2 key=$3 value=$4 start end n line pre inner post t
  start=$(awk -v t="$table" '
    { l = $0; sub(/^[[:space:]]*\[/, "", l) }
    $0 ~ /^[[:space:]]*\[/ && !($0 ~ /^[[:space:]]*\[\[/) {
      sub(/[[:space:]]*\][[:space:]]*(#.*)?$/, "", l)
      if (l == t) {print NR; exit}
    }' "$f")
  [[ -n $start ]] || { anchor_die "no [$table] table in $f (anchor gone)"; return 1; }
  end=$(awk -v s="$start" 'NR>s && /^[[:space:]]*\[/ {print NR - 1; exit}' "$f")
  [[ -n $end ]] || end=$(wc -l <"$f")
  n=$(awk -v s="$start" -v e="$end" -v k="$key" 'NR>s && NR<=e && $0 ~ "^[[:space:]]*" k "[[:space:]]*=" {print NR; exit}' "$f")
  [[ -n $n ]] || { anchor_die "[$table] in $f has no $key line (anchor gone)"; return 1; }
  line=$(sed -n "${n}p" "$f")
  if ! [[ $line =~ ^([[:space:]]*"$key"[[:space:]]*=[[:space:]]*\[)(.*)\]([[:space:]]*(#.*)?)$ ]]; then
    anchor_die "[$table] $key in $f is not a single-line array (fix it by hand, then re-run)"
    return 1
  fi
  pre=${BASH_REMATCH[1]} inner=${BASH_REMATCH[2]} post=${BASH_REMATCH[3]}
  if [[ $inner == *"\"$value\""* || $inner == *"'$value'"* ]]; then return 2; fi
  inner=${inner%"${inner##*[![:space:]]}"}
  inner=${inner%,}
  if [[ -z ${inner//[[:space:]]/} ]]; then inner="\"$value\""; else inner="$inner, \"$value\""; fi
  t=$(mktemp)
  awk -v n="$n" -v r="$pre$inner]$post" 'NR == n {print r; next} {print}' "$f" >"$t"
  anchor_replace "$t" "$f"
}
