#!/usr/bin/env bash
# Test for lib/anchor.sh (plan tn-review-2026-11-04-remediation WP-R6).
#
#   test-anchor.sh
#
# Works on a scratch dir only (mktemp -d, outside every repo). Fixture: a synthetic actions.toml with a
# prefix-sharing id pair, a block with a nested step table, and a final block with no trailing header. Checks:
#   1. anchor_id_line is fully anchored (`a` never matches `a-x`; a missing id exits 1);
#   2. anchor_block_end is the line before the next `[[action]]`, or the last line at EOF (not a step header);
#   3. anchor_has_key sees a key inside the block and not one in a neighbour;
#   4. anchor_insert_after adds exactly one line after the id line and nothing else changes;
#   5. anchor_die prints on stderr and returns 1;
#   6. --help prints usage and exits 0.
# >>> shguard modes=exec (generated by shell-disposition-gate --guard; do not edit)
case $(realpath -- "$0" 2>/dev/null) in */'deploy/migrations/lib/test-anchor.sh') _shguard_m='exec' ;; *) if [ "${SHGUARD_MODE-}" = 'pipe' ]; then _shguard_m='pipe'; else _shguard_m='source'; fi ;; esac
# shellcheck disable=SC2317
case $_shguard_m in
  exec) unset _shguard_m ;;
  *) printf '%s: refusing %s invocation (supports: exec; pipe callers set SHGUARD_MODE=pipe)\n' 'test-anchor.sh' "$_shguard_m" >&2; unset _shguard_m; return 1 2>/dev/null || exit 1 ;;
esac
# <<< shguard
for _a in "$@"; do case "$_a" in --help|-h)
  printf 'usage: %s\n' "${0##*/}"
  awk 'NR>1 && /^#/ {sub(/^# ?/, ""); print; next} NR>1 {exit}' "$0"
  exit 0;; esac; done
. "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../../scripts/lib/build-id.sh"
build_flags "${BASH_SOURCE[0]}" "$@"

set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT

say() { printf '== %s\n' "$*"; }
fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

# shellcheck source=/dev/null
. "$here/anchor.sh"

f=$scratch/actions.toml
cat >"$f" <<'EOF_FIX'
# live actions

[[action]]
id = "a-x"
label = "Prefix twin"
fast = true

[[action]]
id = "a"
label = "A"
[[action.steps]]
type = "lint"

# between
[[action]]
id = "b"
label = "B"
fast = true
[[action.steps]]
type = "guard"
EOF_FIX

say "1. anchor_id_line is fully anchored"
[[ $(anchor_id_line "$f" a) == 9 ]] || fail "a is not line 9"
[[ $(anchor_id_line "$f" a-x) == 4 ]] || fail "a-x is not line 4"
if anchor_id_line "$f" missing >/dev/null; then fail "missing id matched"; fi
if anchor_id_line "$f" a- >/dev/null; then fail "partial id matched"; fi

say "2. anchor_block_end"
[[ $(anchor_block_end "$f" 9) == 14 ]] || fail "a block should end at 14 (before the [[action]] of b), got $(anchor_block_end "$f" 9)"
n=$(wc -l <"$f")
[[ $(anchor_block_end "$f" "$(anchor_id_line "$f" b)") == "$n" ]] || fail "last block should end at EOF"

say "3. anchor_has_key"
anchor_has_key "$f" 4 fast || fail "a-x has fast"
if anchor_has_key "$f" 9 fast; then fail "a has no fast (b's fast leaked in)"; fi
anchor_has_key "$f" "$(anchor_id_line "$f" b)" fast || fail "b has fast"

say "4. anchor_insert_after"
cp -- "$f" "$scratch/orig"
anchor_insert_after "$f" 9 'fast = true'
[[ $(sed -n 10p "$f") == "fast = true" ]] || fail "not inserted after the id line"
grep -v '^fast = true$' "$f" | cmp - <(grep -v '^fast = true$' "$scratch/orig") || fail "rest of the file changed"
[[ $(wc -l <"$f") == $(($(wc -l <"$scratch/orig") + 1)) ]] || fail "expected exactly one added line"
anchor_has_key "$f" 9 fast || fail "a has fast after the insert"

say "5. anchor_die"
rc=0
anchor_die "0000: boom" 2>"$scratch/err" || rc=$?
[[ $rc == 1 ]] || fail "anchor_die status $rc"
grep -q '^    0000: boom$' "$scratch/err" || fail "anchor_die message"

say "6. anchor_array_add vs 0036 / 0039 hosts edits"
loc=$here/../local
sed -n "/<<'EOF_KIND'\$/,/^EOF_KIND\$/{//!p}" "$loc/test-0036.sh" >"$scratch/k36.toml"
awk '/kinds\.toml" <<.EOF_FIX.$/ {on=1; next} on && /^EOF_FIX$/ {exit} on' "$loc/test-0039.sh" >"$scratch/k39.toml"
[[ -s $scratch/k36.toml && -s $scratch/k39.toml ]] || fail "could not extract the kinds fixtures"
export CV_MIGRATIONS_LIB=$here
for hv in 36 39; do
  k=$scratch/k$hv.toml
  # the migration's own edit, run on a copy
  if [[ $hv == 36 ]]; then
    hosts=(m.fanfiction.net www.royalroad.com www.author-site-a.example author-site-b.example)
    ( source "$loc/0036-fanfic-titles.sh"; _0036_wire_hosts "$k" "$scratch/mig$hv.toml" )
  else
    hosts=(www.author-site-a.example author-site-b.example)
    ( source "$loc/0039-public-release-config.sh"; _0039_hosts "$k" "$scratch/mig$hv.toml" )
  fi
  cp -- "$k" "$scratch/lib$hv.toml"
  for h in "${hosts[@]}"; do
    rc=0
    anchor_array_add "$scratch/lib$hv.toml" kinds.fanfic hosts "$h" || rc=$?
    [[ $rc == 0 || $rc == 2 ]] || fail "0$hv: array_add $h status $rc"
  done
  cmp "$scratch/mig$hv.toml" "$scratch/lib$hv.toml" || fail "0$hv: lib result differs from the migration's"
  cp -- "$scratch/lib$hv.toml" "$scratch/once$hv.toml"
  for h in "${hosts[@]}"; do
    rc=0
    anchor_array_add "$scratch/lib$hv.toml" kinds.fanfic hosts "$h" || rc=$?
    [[ $rc == 2 ]] || fail "0$hv: second add of $h status $rc, want 2"
  done
  cmp "$scratch/once$hv.toml" "$scratch/lib$hv.toml" || fail "0$hv: second run changed the file"
  [[ $(grep -c '^hosts' "$scratch/lib$hv.toml") == $(grep -c '^hosts' "$k") ]] || fail "0$hv: hosts lines added or lost"
  grep -qxF 'hosts = ["blog.example"]' "$scratch/lib$hv.toml" || [[ $hv == 36 ]] || fail "0$hv: other kind touched"
done
grep -qxF 'hosts = ["archiveofourown.org", "www.royalroad.com", "m.fanfiction.net", "www.author-site-a.example", "author-site-b.example"]  # mine' "$scratch/lib36.toml" || fail "0036: hosts line wrong"
# changed anchors: status 1, message on stderr, file untouched
chk() { # <label> <sed-script> <table> <key>
  cp -- "$scratch/k39.toml" "$scratch/c.toml"
  sed -i "$2" "$scratch/c.toml"
  cp -- "$scratch/c.toml" "$scratch/c.keep"
  rc=0
  anchor_array_add "$scratch/c.toml" "$3" "$4" new.example 2>"$scratch/err" || rc=$?
  [[ $rc == 1 ]] || fail "$1: status $rc, want 1"
  [[ -s $scratch/err ]] || fail "$1: no message"
  cmp "$scratch/c.keep" "$scratch/c.toml" || fail "$1: file touched"
}
chk "no table" 's/^\[kinds.fanfic\]$/[kinds.story]/' kinds.fanfic hosts
chk "no key" '/^hosts = \["archive/d' kinds.fanfic hosts
chk "multi-line array" 's/^\[kinds.fanfic\]$/[kinds.fanfic]\nhosts = [\n  "x"\n]/;/^hosts = \["archive/d' kinds.fanfic hosts

say "7. --help"
bash "$here/test-anchor.sh" --help | grep -q '^usage:' || fail "--help"
say PASS
