#!/usr/bin/env bash
# Test for lib/anchor.sh (plan tn-review-2026-11-04-remediation WP-R6).
#
#   test-anchor.sh
#
# Works on a scratch dir only (mktemp -d, outside every repo). Fixture: a synthetic actions.toml with a
# prefix-sharing id pair, a block with a nested step table, and a final block with no trailing header. Checks:
#   1. anchor_id_line is fully anchored (`a` never matches `a-x`; a missing id exits 1);
#   2. anchor_block_end is the line before the next `[[action]]`, or the last line at EOF (not a step header);
#   3. anchor_has_key sees a key inside the block and not one in a neighbour;
#   4. anchor_insert_after adds exactly one line after the id line and nothing else changes;
#   5. anchor_die prints on stderr and returns 1;
#   6. --help prints usage and exits 0.
# >>> shguard modes=exec (generated by shell-disposition-gate --guard; do not edit)
case $(realpath -- "$0" 2>/dev/null) in */'deploy/migrations/lib/test-anchor.sh') _shguard_m='exec' ;; *) if [ "${SHGUARD_MODE-}" = 'pipe' ]; then _shguard_m='pipe'; else _shguard_m='source'; fi ;; esac
# shellcheck disable=SC2317
case $_shguard_m in
  exec) unset _shguard_m ;;
  *) printf '%s: refusing %s invocation (supports: exec; pipe callers set SHGUARD_MODE=pipe)\n' 'test-anchor.sh' "$_shguard_m" >&2; unset _shguard_m; return 1 2>/dev/null || exit 1 ;;
esac
# <<< shguard
for _a in "$@"; do case "$_a" in --help|-h)
  printf 'usage: %s\n' "${0##*/}"
  awk 'NR>1 && /^#/ {sub(/^# ?/, ""); print; next} NR>1 {exit}' "$0"
  exit 0;; esac; done
. "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../../scripts/lib/build-id.sh"
build_flags "${BASH_SOURCE[0]}" "$@"

set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT

say() { printf '== %s\n' "$*"; }
fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

# shellcheck source=/dev/null
. "$here/anchor.sh"

f=$scratch/actions.toml
cat >"$f" <<'EOF_FIX'
# live actions

[[action]]
id = "a-x"
label = "Prefix twin"
fast = true

[[action]]
id = "a"
label = "A"
[[action.steps]]
type = "lint"

# between
[[action]]
id = "b"
label = "B"
fast = true
[[action.steps]]
type = "guard"
EOF_FIX

say "1. anchor_id_line is fully anchored"
[[ $(anchor_id_line "$f" a) == 9 ]] || fail "a is not line 9"
[[ $(anchor_id_line "$f" a-x) == 4 ]] || fail "a-x is not line 4"
if anchor_id_line "$f" missing >/dev/null; then fail "missing id matched"; fi
if anchor_id_line "$f" a- >/dev/null; then fail "partial id matched"; fi

say "2. anchor_block_end"
[[ $(anchor_block_end "$f" 9) == 14 ]] || fail "a block should end at 14 (before the [[action]] of b), got $(anchor_block_end "$f" 9)"
n=$(wc -l <"$f")
[[ $(anchor_block_end "$f" "$(anchor_id_line "$f" b)") == "$n" ]] || fail "last block should end at EOF"

say "3. anchor_has_key"
anchor_has_key "$f" 4 fast || fail "a-x has fast"
if anchor_has_key "$f" 9 fast; then fail "a has no fast (b's fast leaked in)"; fi
anchor_has_key "$f" "$(anchor_id_line "$f" b)" fast || fail "b has fast"

say "4. anchor_insert_after"
cp -- "$f" "$scratch/orig"
anchor_insert_after "$f" 9 'fast = true'
[[ $(sed -n 10p "$f") == "fast = true" ]] || fail "not inserted after the id line"
grep -v '^fast = true$' "$f" | cmp - <(grep -v '^fast = true$' "$scratch/orig") || fail "rest of the file changed"
[[ $(wc -l <"$f") == $(($(wc -l <"$scratch/orig") + 1)) ]] || fail "expected exactly one added line"
anchor_has_key "$f" 9 fast || fail "a has fast after the insert"

say "5. anchor_die"
rc=0
anchor_die "0000: boom" 2>"$scratch/err" || rc=$?
[[ $rc == 1 ]] || fail "anchor_die status $rc"
grep -q '^    0000: boom$' "$scratch/err" || fail "anchor_die message"

say "6. --help"
bash "$here/test-anchor.sh" --help | grep -q '^usage:' || fail "--help"
say PASS
