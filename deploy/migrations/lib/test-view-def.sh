#!/usr/bin/env bash
# Test for lib/view-def.sh (plan tn-review-2026-11-10-remediation WP-R9).
#
#   test-view-def.sh
#
# Scratch dir only. Replays the fixtures that test-0035.sh and test-0040.sh seed (their EOF_FIX heredocs and
# drop-* variants, extracted from those files) through the lib and asserts the lib's output is byte-identical to
# what the REAL migrations (0035, 0040: migrate_stopped, run on a scratch copy) produce on the same input. Each
# migration is covered for: the first run (byte-identical to the migration's result, with the `backup:` line and a
# backup equal to the original), a second run (no change, no backup, "already applied"), and a changed anchor
# (viewdef_apply returns non-zero, the file is untouched, no backup). Also: viewdef_add_props appends only the
# missing blocks, and --help.
# shellcheck disable=SC2154  # here, repo, scratch, BACKUP_DIR are set by lib/test-harness.sh
# >>> shguard modes=exec (generated by shell-disposition-gate --guard; do not edit)
case $(realpath -- "$0" 2>/dev/null) in */'deploy/migrations/lib/test-view-def.sh') _shguard_m='exec' ;; *) if [ "${SHGUARD_MODE-}" = 'pipe' ]; then _shguard_m='pipe'; else _shguard_m='source'; fi ;; esac
# shellcheck disable=SC2317
case $_shguard_m in
  exec) unset _shguard_m ;;
  *) printf '%s: refusing %s invocation (supports: exec; pipe callers set SHGUARD_MODE=pipe)\n' 'test-view-def.sh' "$_shguard_m" >&2; unset _shguard_m; return 1 2>/dev/null || exit 1 ;;
esac
# <<< shguard
. "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/test-harness.sh"
. "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../../scripts/lib/build-id.sh"
build_flags "${BASH_SOURCE[0]}" "$@"
set -euo pipefail

# shellcheck source=/dev/null
. "$here/view-def.sh"
loc=$here/../local

FORMULA='access = '\''if(note.complete == false || ((note.access == "paid" || note.access == "founding") && note.complete != true), "🔒", "")'\'''
LABELS=("file.name|Note" "formula.access|Access" "note.publication|Publication" "formula.tags|Tags"
  "note.word-count|Words" "formula.minutes|Minutes" "note.created|Created")

# The edits a migration written on the lib would declare.
edit35() {
  viewdef_add_formula "$1" read "$FORMULA" &&
    viewdef_order_insert "$1" "Reading List" file.name formula.access &&
    viewdef_add_props "$1" formula.access Access
}
edit40() {
  local pair
  viewdef_add_formula "$1" minutes "$FORMULA" &&
    viewdef_order_insert "$1" Unread file.name formula.access &&
    viewdef_order_insert "$1" Unread formula.access note.publication || return 1
  for pair in "${LABELS[@]}"; do viewdef_add_props "$1" "${pair%%|*}" "${pair#*|}" || return 1; done
}

# seed <test-file> <variant> <live-path>: the test's own fixture heredoc plus its drop-* sed.
seed() {
  mkdir -p "$(dirname "$3")"
  sed -n "/<<'EOF_FIX'\$/,/^EOF_FIX\$/{//!p}" "$loc/$1" >"$3"
  [[ -s $3 ]] || fail "could not extract the fixture of $1"
  case $2 in
    drop-read) sed -i '/^read = /d' "$3" ;;
    drop-minutes) sed -i '/^minutes = /d' "$3" ;;
    drop-filename-35) sed -i 's/"file.name", //' "$3" ;;
    drop-filename-40) sed -i '0,/"file.name", /s///' "$3" ;;
    none) ;;
  esac
}

# replay <num> <live-name> <edit-fn> <drop-formula-variant> <drop-filename-variant>
replay() {
  local num=$1 name=$2 fn=$3 dropf=$4 dropn=$5 d out stray
  local mig=("$loc"/00"$num"-*.sh)
  say "$num. first run: lib vs the real migration"
  d=$scratch/m$num; seed "test-00$num.sh" none "$d/views/$name"
  cp -- "$d/views/$name" "$scratch/orig$num.toml"
  (
    export CONFIG_DIR=$d BACKUP_DIR=$d/bak
    # shellcheck source=/dev/null
    source "${mig[0]}"
    migrate_stopped >/dev/null
  )
  d=$scratch/l$num; seed "test-00$num.sh" none "$d/views/$name"
  export BACKUP_DIR=$d/bak
  out=$(viewdef_apply "$d/views/$name" "$fn")
  echo "$out"
  cmp "$scratch/m$num/views/$name" "$d/views/$name" || fail "$num: lib result differs from the migration's"
  grep -q "    backup: $BACKUP_DIR/$name" <<<"$out" || fail "$num: no backup line"
  cmp "$BACKUP_DIR/$name" "$scratch/orig$num.toml" || fail "$num: backup is not the original"
  cmp -s "$d/views/$name" "$scratch/orig$num.toml" && fail "$num: nothing changed"

  say "$num. second run: byte-identical, no backup"
  cp -- "$d/views/$name" "$scratch/after$num.toml"
  rm -rf "$BACKUP_DIR"
  out=$(viewdef_apply "$d/views/$name" "$fn")
  echo "$out"
  cmp "$scratch/after$num.toml" "$d/views/$name" || fail "$num: second run changed the file"
  ! grep -q backup: <<<"$out" || fail "$num: no-op run backed up"
  grep -q 'already applied' <<<"$out" || fail "$num: no already-applied log"
  [[ ! -e $BACKUP_DIR ]] || fail "$num: no-op run created a backup dir"

  say "$num. changed anchor: non-zero, untouched"
  for v in "$dropf" "$dropn"; do
    d=$scratch/x$num$v; seed "test-00$num.sh" "$v" "$d/views/$name"
    cp -- "$d/views/$name" "$scratch/keep.toml"
    export BACKUP_DIR=$d/bak
    rc=0
    viewdef_apply "$d/views/$name" "$fn" >/dev/null 2>"$scratch/err" || rc=$?
    [[ $rc == 1 ]] || fail "$num/$v: status $rc, want 1"
    grep -q 'anchor gone' "$scratch/err" || fail "$num/$v: no anchor-gone message"
    cmp "$scratch/keep.toml" "$d/views/$name" || fail "$num/$v: file edited despite a gone anchor"
    [[ ! -e $BACKUP_DIR ]] || fail "$num/$v: refusal backed up"
    stray=$(shopt -s dotglob nullglob; for e in "$d/views"/*; do [[ ${e##*/} == "$name" ]] || printf '%s\n' "${e##*/}"; done)
    [[ -z $stray ]] || fail "$num/$v: temp file left behind"
  done
}

replay 35 daily-reading-list.toml edit35 drop-read drop-filename-35
replay 40 monthly-reading.toml edit40 drop-minutes drop-filename-40

say "viewdef_add_props appends only the missing blocks, at EOF"
f=$scratch/p.toml
printf '[properties."a.b"]\ndisplayName = "Old"\n' >"$f"
viewdef_add_props "$f" a.b New
viewdef_add_props "$f" c.d Dee
[[ $(cat "$f") == $'[properties."a.b"]\ndisplayName = "Old"\n\n[properties."c.d"]\ndisplayName = "Dee"' ]] || fail "props result: $(cat "$f")"

say "--help"
bash "$here/test-view-def.sh" --help | grep -q '^usage: test-view-def.sh' || fail "--help usage missing"

say "PASS"
