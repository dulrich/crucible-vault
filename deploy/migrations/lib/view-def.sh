viewdef_add_formula() {
  local f=$1 after=$2 line=$3 key t has anchor
  key=${line%% = *}
  read -r has anchor < <(awk -v k="$key" -v a="$after" '
    /^\[/ { sec = ($0 ~ /^\[formulas\][ \t]*$/) ? "F" : "O"; next }
    sec == "F" {
      if (index($0, k " = ") == 1) has = 1
      if (index($0, a " = ") == 1) anchor = 1
    }
    END { printf "%d %d\n", has + 0, anchor + 0 }' "$f")
  [[ $has == 1 ]] && return 0
  [[ $anchor == 1 ]] || { anchor_die "the [formulas] \`$after = \` anchor gone in $f"; return 1; }
  t=$(mktemp)
  awk -v a="$after" -v formula="$line" '
    /^\[/ { sec = ($0 ~ /^\[formulas\][ \t]*$/) ? "F" : "O"; print; next }
    sec == "F" && !done && index($0, a " = ") == 1 { print; print formula; done = 1; next }
    { print }' "$f" >"$t"
  anchor_replace "$t" "$f"
}

viewdef_order_insert() {
  local f=$1 view=$2 after=$3 new=$4 t has anchor
  read -r has anchor < <(awk -v v="name = \"$view\"" -v a="\"$after\", " -v w="\"$new\"" '
    /^\[/ { if ($0 ~ /^\[\[views\]\]/) { sec = "V"; inview = 0; seen = 0 } else sec = "O"; next }
    sec == "V" {
      if ($0 ~ /^name = / && $0 ~ ("^" v "[ \t]*$")) inview = 1
      else if (inview && !seen && $0 ~ /^order = \[/) {
        seen = 1
        if (index($0, w)) has = 1
        if (index($0, a)) anchor = 1
      }
    }
    END { printf "%d %d\n", has + 0, anchor + 0 }' "$f")
  [[ $has == 1 ]] && return 0
  [[ $anchor == 1 ]] || { anchor_die "the $view \`order = [\"$after\", …\` anchor gone in $f"; return 1; }
  t=$(mktemp)
  awk -v v="name = \"$view\"" -v a="\"$after\", " -v text="\"$new\", " '
    /^\[/ { if ($0 ~ /^\[\[views\]\]/) { sec = "V"; inview = 0; seen = 0 } else sec = "O"; print; next }
    sec == "V" {
      if ($0 ~ /^name = / && $0 ~ ("^" v "[ \t]*$")) inview = 1
      else if (inview && !seen && $0 ~ /^order = \[/) {
        seen = 1
        i = index($0, a)
        n = i + length(a) - 1
        $0 = substr($0, 1, n) text substr($0, n + 1)
      }
    }
    { print }' "$f" >"$t"
  anchor_replace "$t" "$f"
}

viewdef_add_props() {
  local f=$1 key=$2 label=$3 t
  if grep -qE "^\[properties\.\"${key//./\\.}\"\][[:space:]]*\$" "$f"; then return 0; fi
  t=$(mktemp)
  awk -v key="$key" -v label="$label" '
    { print }
    END { printf "\n[properties.\"%s\"]\ndisplayName = \"%s\"\n", key, label }' "$f" >"$t"
  anchor_replace "$t" "$f"
}

viewdef_apply() {
  local f=$1 fn=$2 t
  shift 2
  t=$(mktemp "$(dirname -- "$f")/.viewdef.XXXXXX")
  cat -- "$f" >"$t"
  if ! "$fn" "$t" "$@"; then
    rm -f -- "$t"
    return 1
  fi
  if cmp -s -- "$t" "$f"; then
    rm -f -- "$t"
    echo "    $f already applied — left untouched"
    return 0
  fi
  backup "$f"
  anchor_replace "$t" "$f"
}
