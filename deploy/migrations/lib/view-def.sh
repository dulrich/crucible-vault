# Edit functions work in place on the file they are given (a temp copy, when called through viewdef_apply) and
# share one status: 0 = done or already applied (the file is unchanged when already applied), 1 = anchor gone
# (message on stderr, file untouched). Each skips when its target already holds.
#
#   viewdef_add_formula <file> <after-key> <line>      insert <line> (`key = 'expr'`) after the `<after-key> = `
#                                   line inside `[formulas]`; skipped when a `<key> = ` line is already there
#   viewdef_order_insert <file> <view> <after> <new>   in the first `order = [` line of the `[[views]]` named
#                                   <view>, insert `"<new>", ` after `"<after>", `; skipped when "<new>" is listed
#   viewdef_add_props <file> <key> <label>             append `[properties."<key>"]` + `displayName = "<label>"`
#                                   at EOF (after a blank line); skipped when that header exists
#   viewdef_apply <file> <edit-fn> [args...]           the skeleton: run `<edit-fn> <tmp> [args...]` on a temp copy
#                                   (it calls the functions above on "$1"); when it fails, <file> is untouched and
#                                   apply returns 1; when it changed nothing, no backup and no write (log
#                                   "already applied"); otherwise `backup <file>` then replace <file>'s content
